#!/usr/bin/env python3
"""Build unmodified upstream native sources in an isolated, ignored copy.

Run inside `nix develop .#reference`; Nix supplies FLINT/GMP/MPFR instead of
upstream's network-fetching hepware Makefile. No production symGCAD code uses
this Python build helper or the resulting extension.
"""
import argparse
import hashlib
import json
import os
import pathlib
import shutil
import subprocess
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default="DO_NOT_PUSH_REFERENCES/gcad")
    parser.add_argument("--destination", default=".reference/gcad")
    args = parser.parse_args()
    source = pathlib.Path(args.source).resolve()
    destination = pathlib.Path(args.destination).resolve()
    if source == destination or source in destination.parents:
        parser.error("destination must be separate from the reference checkout")
    revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
    shutil.copytree(source, destination, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns(".git", "__pycache__", "build", "*.so", "*.egg-info", "hepware"))
    hashes = {str(p.relative_to(source)): hashlib.sha256(p.read_bytes()).hexdigest()
              for sub in ["gcad", "gcad_ext", "tests"] for p in sorted((source/sub).rglob("*"))
              if p.is_file() and p.suffix in (".py", ".pyx", ".cpp")}
    # Read the upstream extension configuration but avoid its setup.py hook,
    # whose sole extra purpose is downloading/building dependencies via make.
    script = r'''
from setuptools import Extension, setup
from Cython.Build import cythonize
extension = Extension("gcad_ext", ["gcad_ext/gcad_ext.pyx"], language="c++",
    libraries=["flint", "mpfr", "gmp"],
    extra_compile_args=["-O3", "-std=c++17", "-Wno-unused-function", "-UNDEBUG", "-fdata-sections", "-ffunction-sections"],
    extra_link_args=["-Wl,--gc-sections"])
setup(name="gcad", version="0.0+reference", packages=["gcad"],
      ext_modules=cythonize([extension], compiler_directives={"language_level": 3}),
      script_args=["build_ext", "--inplace"])
'''
    env = dict(os.environ, SETUPTOOLS_SCM_PRETEND_VERSION="0.0+reference")
    subprocess.run([sys.executable, "-c", script], cwd=destination, env=env, check=True)
    # This is normally generated by setuptools-scm's setup.py integration.
    (destination/"gcad"/"_version.py").write_text('__version__ = "0.0+reference"\n')
    subprocess.run([sys.executable, "-c", "import gcad.gcad as g; import gcad_ext; assert g.RSFC is gcad_ext.RSFC"], cwd=destination, check=True)
    metadata = dict(schema_version=1, revision=revision, source=str(source), destination=str(destination),
                    python=sys.version, python_executable=sys.executable,
                    compiler=subprocess.check_output(["c++", "--version"], text=True).splitlines()[0],
                    compile_flags=["-O3", "-std=c++17", "-UNDEBUG"], hashes=hashes)
    (destination.parent/"provenance.json").write_text(json.dumps(metadata, indent=2)+"\n")
    print(json.dumps({k:v for k,v in metadata.items() if k != "hashes"}, indent=2))


if __name__ == "__main__":
    main()
